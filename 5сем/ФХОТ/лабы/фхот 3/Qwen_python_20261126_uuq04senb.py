# -*- coding: utf-8 -*-
"""Выводы по ЛР (п.2.5 и 2.6), вариант 10 Si-P. Оформление по ГОСТ 7.32/2.105."""
import re
from docx import Document
from docx.shared import Pt, Mm, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_TAB_ALIGNMENT
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

FONT, SIZE, SIZE_TAB = 'Times New Roman', Pt(14), Pt(12)
SPACING, ABZAC = 1.5, Cm(1.25)
M_L, M_R, M_T, M_B = Mm(30), Mm(15), Mm(20), Mm(20)
W_TXT = 165
TOKEN = re.compile(r'(\^\{[^}]*\}|_\{[^}]*\})')

def setup(doc):
    sec = doc.sections[0]
    sec.left_margin, sec.right_margin = M_L, M_R
    sec.top_margin, sec.bottom_margin = M_T, M_B
    st = doc.styles['Normal']
    st.font.name, st.font.size = FONT, SIZE
    rf = st.element.get_or_add_rPr().get_or_add_rFonts()
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rf.set(qn(a), FONT)
    pf = st.paragraph_format
    pf.line_spacing, pf.alignment = SPACING, WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.space_before = pf.space_after = Pt(0)

def add_rich(p, text, bold=False, italic=False, size=None):
    for part in TOKEN.split(text):
        if not part:
            continue
        sup = sub = False
        if part.startswith('^{'):
            sup, part = True, part[2:-1]
        elif part.startswith('_{'):
            sub, part = True, part[2:-1]
        r = p.add_run(part)
        r.bold, r.italic = bold, italic
        r.font.superscript, r.font.subscript = sup, sub
        r.font.name = FONT
        if size:
            r.font.size = size

def par(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=ABZAC,
        bold=False, italic=False, size=None, before=0, after=0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment, pf.first_line_indent = align, indent
    pf.line_spacing = SPACING
    pf.space_before, pf.space_after = Pt(before), Pt(after)
    if text:
        add_rich(p, text, bold, italic, size)
    return p

def head(doc, text, level=1):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing, pf.first_line_indent = SPACING, Cm(0)
    pf.space_before = pf.space_after = Pt(12)
    if level == 1:
        pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
        add_rich(p, text.upper(), bold=True)
    else:
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        add_rich(p, text, bold=True)

def formula(doc, text, num=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing, pf.first_line_indent = SPACING, Cm(0)
    pf.space_before = pf.space_after = Pt(6)
    pf.tab_stops.add_tab_stop(Mm(W_TXT / 2), WD_TAB_ALIGNMENT.CENTER)
    if num:
        pf.tab_stops.add_tab_stop(Mm(W_TXT), WD_TAB_ALIGNMENT.RIGHT)
        add_rich(p, '\t' + text + '\t(%d)' % num)
    else:
        add_rich(p, '\t' + text)

def table(doc, caption, header, rows):
    par(doc, caption, align=WD_ALIGN_PARAGRAPH.CENTER, indent=Cm(0),
        bold=True, after=6)
    t = doc.add_table(rows=1, cols=len(header))
    t.style, t.alignment = 'Table Grid', WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(header):
        cp = t.rows[0].cells[j].paragraphs[0]
        cp.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.paragraph_format.line_spacing = 1.0
        add_rich(cp, h, bold=True, size=SIZE_TAB)
    for row in rows:
        for j, val in enumerate(t.add_row().cells):
            cp = val.paragraphs[0]
            cp.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
            cp.paragraph_format.line_spacing = 1.0
            add_rich(cp, row[j], size=SIZE_TAB)

def page_number(doc):
    p = doc.sections[0].footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fld = OxmlElement('w:fldSimple')
    fld.set(qn('w:instr'), 'PAGE')
    r = OxmlElement('w:r')
    t = OxmlElement('w:t'); t.text = '1'
    r.append(t); fld.append(r); p._p.append(fld)

