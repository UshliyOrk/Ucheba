% Лабораторная работа 5, вариант 1
% Широкополосное согласование нагрузки и СВЧ-генератора

clear; clc;

% Исходные данные
Z_n   = 70;          % сопротивление нагрузки, Ом
f     = 2e9;         % частота, Гц
h     = 0.5e-3;      % толщина подложки, м
eps_r = 9.8;         % относительная диэлектрическая проницаемость
Z_in  = 50;          % волновое сопротивление подводящей линии, Ом
c     = 3e8;         % скорость света, м/с

% Волновые сопротивления трансформаторов
Z_tr  = sqrt(Z_n * Z_in);                 % одноступенчатый
Z_tr1 = (Z_n * Z_in^3)^0.25;              % двухступенчатый, 1-я ступень
Z_tr2 = (Z_in * Z_n^3)^0.25;              % двухступенчатый, 2-я ступень

Z_list = [Z_tr, Z_tr1, Z_tr2];
names  = {'Z_tr (1 ступень)', 'Z_tr1 (2 ступени)', 'Z_tr2 (2 ступени)'};

% Длина волны в свободном пространстве
lambda0 = c / f;

fprintf('Результаты расчёта для варианта 1:\n');
fprintf('------------------------------------------------------------\n');

for i = 1:length(Z_list)
    Z = Z_list(i);

    % Вспомогательные коэффициенты A и B
    A = (Z/60) * sqrt((eps_r + 1)/2) + ...
        (eps_r - 1)/(eps_r + 1) * (0.23 + 0.11/eps_r);
    B = 60 * pi^2 / (Z * sqrt(eps_r));

    % Отношение w/h
    if A > 1.52
        wh = 8 * exp(A) / (exp(2*A) - 2);
    else
        wh = (2/pi) * ( B - 1 - log(2*B - 1) + ...
             (eps_r - 1)/(2*eps_r) * ( log(B - 1) + 0.39 - 0.61/eps_r ) );
    end

    % Ширина полоска
    w = wh * h;

    % Эффективная диэлектрическая проницаемость
    eps_eff = (eps_r + 1)/2 + (eps_r - 1)/2 / sqrt(1 + 10*h/w);

    % Длина волны в МПЛ и длина четвертьволнового отрезка
    lambda = lambda0 / sqrt(eps_eff);
    l = lambda / 4;

    % Вывод результатов
    fprintf('%s:\n', names{i});
    fprintf('  Z = %.3f Ом\n', Z);
    fprintf('  w/h = %.4f\n', wh);
    fprintf('  w = %.4f мм\n', w*1e3);
    fprintf('  eps_eff = %.4f\n', eps_eff);
    fprintf('  lambda = %.4f мм\n', lambda*1e3);
    fprintf('  l = lambda/4 = %.4f мм\n\n', l*1e3);
end
