# ==========================================

def generate_images():
    # График гигантского импульса (Слайд 4)
    fig, ax = plt.subplots(figsize=(8, 5))
    t = np.linspace(0, 10, 500)
    # Имитация накачки и гигантского импульса
    power = np.zeros_like(t)
    pump_phase = t < 7
    power[pump_phase] = 0.05 * t[pump_phase] # Медленный рост инверсии (условно)
    
    # Гигантский импульс
    pulse_center = 7.2
    pulse_width = 0.15
    power += 5.0 * np.exp(-((t - pulse_center) ** 2) / (2 * pulse_width ** 2))
    
    ax.plot(t, power, color='red', linewidth=2)
    ax.fill_between(t, power, color='red', alpha=0.3)
    
    ax.set_title('Гигантский импульс при модуляции добротности', fontsize=14, fontweight='bold')
    ax.set_xlabel('Время (условные единицы)', fontsize=12)
    ax.set_ylabel('Мощность излучения', fontsize=12)
    ax.set_ylim(0, 6)
    ax.grid(True, linestyle='--', alpha=0.6)
    
    # Аннотации
    ax.annotate('Накачка среды\n(Добротность низкая)', xy=(3, 0.15), xytext=(1.5, 2),
                arrowprops=dict(facecolor='black', shrink=0.05, width=1.5, headwidth=8), fontsize=10)
    ax.annotate('Резкий скачок добротности', xy=(7, 0.5), xytext=(7.5, 3),
                arrowprops=dict(facecolor='black', shrink=0.05, width=1.5, headwidth=8), fontsize=10)
    ax.annotate('Гигантский импульс\n(Наносекунды)', xy=(7.2, 4.5), xytext=(8, 5),
                arrowprops=dict(facecolor='red', shrink=0.05, width=1.5, headwidth=8), fontsize=10, color='red')

    plt.tight_layout()
    plt.savefig('q_switch_graph.png', dpi=150)
    plt.close()

